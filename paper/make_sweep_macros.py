"""Macros for the two risk-tolerance sweeps (src/model/results/rho_sweep40_v33_s{0,1}.json): for each sweep the largest regime
number lambda*sigma_W(z_N) at which the gain of z_A over the strip plan is at most 0.05% of E(z_N), and the gain and Beck's cost
at the regime numbers nearest 0.5, 1, 2, 4 and 8. Writes sections/results_numbers_sweep.tex (\\sweep...) and the ranges over
both sweeps to sections/results_numbers_sweep_summary.tex (\\Sweep...)."""
import json, os, sys
HERE = os.path.dirname(os.path.abspath(__file__)); RES = os.path.join(HERE, "..", "src", "model", "results")
sys.path.insert(0, os.path.dirname(RES))
from supplement_figures import sweep_macros
W = {0: "Zero", 1: "One"}
L = ["% generated by make_sweep_macros.py; do not edit"]
put = lambda n, v: L.append(f"\\newcommand{{\\sweep{n}}}{{{v}}}")
neg_all = []
sweeps = []
for s in (0, 1):
    d = json.load(open(os.path.join(RES, f"rho_sweep40_v33_s{s}.json")))
    assert d.get("model_version") == "v3.3", "sweep model version"
    assert d.get("solver_rev") == "s2", "sweep solver revision"
    assert d["seed"] == s and sorted(r["rho"] for r in d["rows"]) == [25, 50, 100, 200, 300, 500, 1000, 3000, 10000], "incomplete sweep"
    sweeps.append(d)
    rows = sorted(d["rows"], key=lambda r: r["rn_lam_sigma"])
    g = lambda r: 100 * r["ce_gain"] / abs(r["rn_enpv"]); c = lambda r: 100 * r["enpv_cost"] / abs(r["rn_enpv"])
    neg = max((r["rn_lam_sigma"] for r in rows if g(r) <= 0.05), default=float("nan")); neg_all.append(neg)
    put(f"NegligibleMaxLs{W[s]}", f"{neg:.2f}")
    put(f"CostAboveGainAll{W[s]}", "yes" if all(c(r) >= g(r) - 1e-9 for r in rows) else "no")
    for target, name in ((0.5, "Half"), (1, "One"), (2, "Two"), (4, "Four"), (8, "Eight")):
        r = min(rows, key=lambda r: abs(r["rn_lam_sigma"] - target))
        put(f"Gain{name}{W[s]}", f"{g(r):.2f}"); put(f"Cost{name}{W[s]}", f"{c(r):.2f}"); put(f"Ls{name}{W[s]}", f"{r['rn_lam_sigma']:.2f}"); put(f"Rho{name}{W[s]}", f"{r['rho']:,.0f}")
    put(f"RhoMin{W[s]}", f"{rows[-1]['rho']:,.0f}"); put(f"RhoMax{W[s]}", f"{rows[0]['rho']:,.0f}")
put("NegligibleMaxLsMin", f"{min(neg_all):.2f}"); put("NegligibleMaxLsMax", f"{max(neg_all):.2f}")
summary_lines = []
for name, value, comment in sweep_macros(sweeps):
    summary_lines.extend([f"% {comment}", f"\\newcommand{{\\{name}}}{{{value}}}"])
open(os.path.join(HERE, "sections", "results_numbers_sweep.tex"), "w").write("\n".join(L) + "\n")
open(os.path.join(HERE, "sections", "results_numbers_sweep_summary.tex"), "w").write("\n".join(summary_lines) + "\n")
print(len(L) - 1, "sweep macros; negligible up to", neg_all)
print(len(summary_lines) // 2, "sweep summary macros")
